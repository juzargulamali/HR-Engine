/**
 * REVIEWED, staff-facing guidance for "How do I ...?" questions. This is the ONLY app knowledge JARVIS answers from. It is written for people (plain words, the screens they
 * click), it is short on purpose, and every statement in it was checked against how the screens behave (docs/enginious-os/02-screens-and-navigation.md and the Sales references);
 * where something is not certain it is simply not said. It is NOT the internal map, the action catalogue or any code: it contains no code paths, SQL, migration names or
 * permission internals, and a test keeps it that way. Links are real screen paths; a test checks each one against the app's routes.
 *
 * Adding a topic: write it for a colleague, keep `summary` to a couple of sentences, put the clicks in `steps`, link only to screens that exist, add keywords people really use.
 * Modules that JARVIS cannot act in yet (Projects, Inventory, People & HR) get "where to find it" guidance only: JARVIS never reads their records.
 */
import { PUBLISHED_GUIDANCE } from "../knowledge/published.generated";
import { buildIndex, matchByMeaning, type GuidanceIndex } from "./match";

export interface GuidanceLink { label: string; href: string }
export interface GuidanceEntry {
  id: string;
  area: "sales" | "projects" | "inventory" | "people" | "finance" | "general";
  title: string;
  /** Words and short phrases people use for this (matched in lower case). */
  keywords: string[];
  summary: string;
  steps: string[];
  links: GuidanceLink[];
  /** The screens this guide is written FOR, as route patterns (e.g. "/sales/events/[id]"). */
  screens?: string[];
}

/** The published topics of the Map (docs/enginious-os/staff-guidance), generated by scripts/build-jarvis-knowledge.mjs. */
export const GUIDANCE: GuidanceEntry[] = PUBLISHED_GUIDANCE;

let index: GuidanceIndex | null = null;
/** The index of the published guidance (built once). The navigation's own names for the screens are added by lib/jarvis/help/screens.ts when it is loaded. */
export function guidanceIndex(screenNames?: (screen: string) => string | null): GuidanceIndex {
  if (screenNames) index = buildIndex(GUIDANCE, screenNames);
  return (index ??= buildIndex(GUIDANCE));
}

/** The guide(s) that answer a question, best first, matched by meaning (lib/jarvis/help/match.ts). Empty when nothing fits. An ambiguous question returns its candidates. */
export function matchGuidance(question: string, limit = 2, screen: string | null = null): GuidanceEntry[] {
  const m = matchByMeaning(guidanceIndex(), question, screen);
  return m.kind === "answer" ? m.entries.slice(0, limit) : m.kind === "ambiguous" ? m.options.slice(0, limit) : [];
}

